// Dry run of the staged upload flow (stage: 'upload'), with screenshots of each state
import path from 'node:path'
import { openEditor } from './editor-session.mjs'
const { browser, page } = await openEditor({ scale: 1, stage: 'upload' })
const W = (ms) => new Promise((r) => setTimeout(r, ms))
const btn = (re) => page.evaluate((src) => { const rx = new RegExp(src, 'i'); const b = [...document.querySelectorAll('button')].find((x) => rx.test(x.innerText.trim()) && x.getBoundingClientRect().width > 0); if (!b) return null; const r = b.getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2] }, re.source)
await W(1500)
await page.screenshot({ path: 'shots/up-1-empty.png' })
const u = await btn(/^Upload Video$/); console.log('upload btn', u)
await page.mouse.click(...u); await W(1200)
await page.screenshot({ path: 'shots/up-2-modal.png' })
const dz = await page.evaluate(() => { const r = document.querySelector('[role=dialog] input[type=file]').getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2] })
console.log('dropzone', dz)
const [chooser] = await Promise.all([page.waitForFileChooser(), page.mouse.click(...dz)])
await chooser.accept([path.resolve('mock/upload/morning-walk.mov')]); await W(1200)
await page.screenshot({ path: 'shots/up-3-settings.png' })
const g = await btn(/Generate Captions/); console.log('generate', g)
await page.mouse.click(...g); await W(4000)
await page.screenshot({ path: 'shots/up-4-generating.png' })
await page.evaluate(() => window.__finishUpload()); await W(2500)
await page.evaluate(async () => { const v = document.querySelector('video'); v.muted = true; await v.play() }); await W(1500)
await page.screenshot({ path: 'shots/up-5-editor.png' })
console.log('url', page.url())
await browser.close()
